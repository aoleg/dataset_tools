def render_to(res: Result, dest: Path, resample: int) -> None:
    """Crop and resize the ORIGINAL source into res.bucket and save it at dest.

    --optimize relocates images by calling this again on the source file, never
    by rescaling the already-downsized output.
    """
    img, _fmt, _qt = load_source(res.path)
    try:
        # Crop and resize in one pass; the filter operates directly on the crop
        # region. No intermediate image, no extra rounding.
        out = img.resize(res.bucket, resample=resample, box=res.box)
    finally:
        img.close()
    # No exif=, no icc_profile=: EXIF is not carried to the output, which is
    # what prevents orientation being applied twice by downstream viewers.
    if dest.suffix.lower() == ".png":
        out.save(dest, "PNG", compress_level=6)
    else:
        out.save(dest, "JPEG", quality=97, subsampling=0, optimize=True)
    out.close()


def write_output(res: Result, out_dir: Path, resample: int, ext: str) -> None:
    render_to(res, out_dir / (res.out_stem + ext), resample)
    if res.caption_src is not None:
        shutil.copyfile(res.caption_src, out_dir / f"{res.out_stem}.txt")


# ---------------------------------------------------------------------------
# Bucket merging
# ---------------------------------------------------------------------------
#
# Assigning each image to its nearest aspect-ratio family is the right first
# answer, but on a real folder it leaves a long tail: a bucket with three images
# in it trains in batches of three no matter what batch_size says. This pass
# consolidates that tail before anything is written.
#
# It runs entirely in memory, on the assignments the preliminary report
# describes, and only ever changes which bucket an image is destined for. It
# never rescales an already-written output: a moved image is rendered from its
# original source into its new bucket, through the same crop_box() seam as any
# other image.
#
# Rules, in order of preference:
#   1. Same tier, healthy bucket (>= MIN_BUCKET_SIZE), nearest by aspect ratio
#      to the SOURCE ratio - which is what actually minimises the extra crop.
#   2. One tier below, same test. Demotion costs 44% of the pixels, so it is
#      only reached when no same-tier bucket will take the image.
#   3. Rescue: images with no reachable healthy bucket are pooled per tier, and
#      if they total MIN_BUCKET_SIZE they merge into whichever of their own
#      buckets can absorb the most of them. This is what fixes a 512 tier
#      sitting at 5/3/1/1/1, where nothing is healthy enough to be a target.
#
# A move is refused if it would crop away more than MERGE_MAX_CROP, if the image
# is too small to fill the destination within UPSCALE_TOLERANCE, or if it would
# flip the image between portrait and landscape. That last rule matters more
# than it looks: 4:5 and 5:4 are only 0.44 apart in linear ratio, so without it
# a portrait photograph gets cropped into a landscape frame - which throws away
# the subject, not just the margins. 1:1 is neutral and accepts either.


@dataclass
class Move:
    res: "Result"
    from_tier: int
    from_bucket: tuple[int, int]
    crop_before: float
    rule: str


def bucket_counts(results: list["Result"]) -> dict[tuple[int, tuple[int, int]], int]:
    counts: dict[tuple[int, tuple[int, int]], int] = defaultdict(int)
    for r in results:
        counts[(r.tier, r.bucket)] += 1
    return counts


def orientation_ok(src_ar: float, bucket: tuple[int, int]) -> bool:
    """A portrait source may only land in a portrait or square bucket, and a
    landscape source in a landscape or square one."""
    bucket_ar = bucket[0] / bucket[1]
    if bucket_ar == 1.0 or src_ar == 1.0:
        return True
    return (src_ar > 1.0) == (bucket_ar > 1.0)


def ar_distance(src_ar: float, bucket: tuple[int, int]) -> float:
    """Distance in log-ratio space, so 4:5 -> 1:1 and 1:1 -> 5:4 read as equally
    far. Linear ratio distance does not: it makes wide targets look closer than
    tall ones by the same factor."""
    return abs(math.log(bucket[0] / bucket[1]) - math.log(src_ar))


def can_accept(res: "Result", bucket: tuple[int, int]) -> tuple[bool, str]:
    if not orientation_ok(res.src_ar, bucket):
        return False, "orientation"
    if not fits_bucket(res.src_w, res.src_h, bucket):
        return False, "too small"
    if crop_cost(res.src_w, res.src_h, bucket) > MERGE_MAX_CROP:
        return False, "crop"
    return True, ""


def merge_candidates(res: "Result", counts: dict, min_size: int):
    """Ranked destinations for one image, plus the reason there are none."""
    tiers = active_tiers()
    start = tiers.index(res.tier)
    ranked = []
    blocked: set[str] = set()
    saw_destination = False
    for penalty, tier in enumerate(tiers[start:start + 2]):
        for family in AR_FAMILIES:
            bucket = bucket_for(tier, family)
            if (tier, bucket) == (res.tier, res.bucket):
                continue
            if counts.get((tier, bucket), 0) < min_size:
                continue
            saw_destination = True
            ok, why = can_accept(res, bucket)
            if not ok:
                blocked.add(why)
                continue
            # same tier first, then nearest to the source aspect ratio
            ranked.append((penalty, ar_distance(res.src_ar, bucket), tier, bucket))
    ranked.sort(key=lambda c: (c[0], c[1], c[2], c[3]))
    if ranked:
        return ranked, ""
    if not saw_destination:
        return [], (f"no bucket with {MIN_BUCKET_SIZE}+ images in this tier "
                    "or the one below")
    reasons = []
    if "orientation" in blocked:
        reasons.append("every healthy bucket in reach is the other orientation")
    if "crop" in blocked:
        reasons.append(f"would crop over {MERGE_MAX_CROP:.0f}%")
    if "too small" in blocked:
        reasons.append("too small to fill it")
    return [], "; ".join(reasons)


def _dissolve_small_buckets(accepted, counts, moves, moved) -> bool:
    changed = False
    small = sorted(((k, n) for k, n in counts.items() if 0 < n < MIN_BUCKET_SIZE),
                   key=lambda kv: (kv[1], kv[0]))
    for key, _n in small:
        members = sorted((r for r in accepted
                          if (r.tier, r.bucket) == key and id(r) not in moved),
                         key=lambda r: r.name)
        for res in members:
            ranked, _reason = merge_candidates(res, counts, MIN_BUCKET_SIZE)
            if not ranked:
                continue
            penalty, _dist, tier, bucket = ranked[0]
            moves.append(Move(res, res.tier, res.bucket, res.crop_pct,
                              "same tier" if penalty == 0 else "one tier below"))
            counts[(res.tier, res.bucket)] -= 1
            counts[(tier, bucket)] += 1
            place(res, tier, bucket)
            res.merged = True
            moved.add(id(res))
            changed = True
    return changed


def _rescue_stranded(accepted, counts, moves, moved) -> bool:
    """Rule 3: pool the images no healthy bucket will take and merge them.

    The 512 tier at 5/3/1/1/1 is the case this exists for - nothing there is
    large enough to be a destination, so rule 1 can never fire and every image
    stays stranded. Rather than picking the biggest bucket and hoping, each
    stranded bucket is tried as the target and the one that can actually absorb
    the most of the others wins, ties going to the smallest total crop.
    """
    changed = False
    for tier in active_tiers():
        stranded = [r for r in accepted
                    if r.tier == tier and id(r) not in moved
                    and counts[(r.tier, r.bucket)] < MIN_BUCKET_SIZE
                    and not merge_candidates(r, counts, MIN_BUCKET_SIZE)[0]]
        if len(stranded) < MIN_BUCKET_SIZE:
            continue          # cannot reach a healthy size even fully merged
        best = None
        for target in sorted({r.bucket for r in stranded}):
            movable = [r for r in stranded if can_accept(r, target)[0]
                       or r.bucket == target]
            if len(movable) < MIN_BUCKET_SIZE:
                continue
            cost = sum(crop_cost(r.src_w, r.src_h, target) for r in movable)
            key = (-len(movable), cost, target)
            if best is None or key < best[0]:
                best = (key, target, movable)
        if best is None:
            continue
        _key, target, movable = best
        for res in movable:
            if res.bucket == target:
                continue
            moves.append(Move(res, res.tier, res.bucket, res.crop_pct, "rescue"))
            counts[(res.tier, res.bucket)] -= 1
            counts[(tier, target)] += 1
            place(res, tier, target)
            res.merged = True
            moved.add(id(res))
            changed = True
    return changed


def merge_pooled() -> bool:
    """Whether small buckets are merged across the whole tree, per tier.

    The pool is what one training folder batches together. AI Toolkit trains a
    _<tier> folder of the --by-tier layout, subfolders and all, as one dataset.
    Musubi reads no subfolders: each folder is its own [[datasets]] block and
    batches never cross blocks, so there the pool stays one folder, whatever
    the layout.
    """
    return _tier_first and _active_buckets is OSTRIS


def plan_merge(accepted: list["Result"]):
    """Consolidate undersized buckets in place.

    Mutates the placement of the results it moves. Returns
    (moves, unmerged, counts_before, counts_after) where `unmerged` is every
    image still sitting in an undersized bucket, paired with why it stayed.
    """
    before = dict(bucket_counts(accepted))
    counts = defaultdict(int, before)
    moves: list[Move] = []
    moved: set[int] = set()

    for _round in range(MERGE_MAX_ROUNDS):
        changed = _dissolve_small_buckets(accepted, counts, moves, moved)
        changed |= _rescue_stranded(accepted, counts, moves, moved)
        if not changed:
            break

    unmerged = []
    for res in sorted(accepted, key=lambda r: r.name):
        if counts[(res.tier, res.bucket)] < MIN_BUCKET_SIZE:
            _ranked, reason = merge_candidates(res, counts, MIN_BUCKET_SIZE)
            unmerged.append((res, reason or "no destination"))

    after = {k: n for k, n in counts.items() if n > 0}
    return moves, unmerged, before, after


