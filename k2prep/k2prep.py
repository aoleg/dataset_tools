@lru_cache(maxsize=None)
def _ijg_scaled_table(q: int) -> tuple[int, ...]:
    scale = 5000 // q if q < 50 else 200 - 2 * q
    return tuple(min(255, max(1, (v * scale + 50) // 100)) for v in STD_LUMA_QT)


def estimate_jpeg_quality(table) -> int | None:
    """Best-fit IJG quality for a luma quantization table, or None if the
    encoder used non-standard tables."""
    t = list(table)
    if len(t) != 64:
        return None
    best_q, best_ssd = 100, None
    for q in range(1, 101):
        std = _ijg_scaled_table(q)
        ssd = 0
        for a, b in zip(std, t):
            d = a - b
            ssd += d * d
        if best_ssd is None or ssd < best_ssd:
            best_q, best_ssd = q, ssd
    energy = sum(v * v for v in t)
    if energy <= 0:
        return None
    if best_ssd / energy > QT_RESIDUAL_MAX:
        return None
    return best_q


def score_q(q_est: int | None) -> int | None:
    if q_est is None:
        return None
    for lo, s in Q_BANDS:
        if q_est >= lo:
            return s
    return 1


