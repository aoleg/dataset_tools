def _threshold_arg(value: str) -> int:
    try:
        n = int(value)
    except ValueError:
        raise argparse.ArgumentTypeError(f"--threshold must be an integer, got {value!r}")
    if not 0 <= n <= 10:
        raise argparse.ArgumentTypeError(f"--threshold must be 0..10, got {n}")
    return n


def _sort_tiers_arg(value: str) -> int:
    try:
        n = int(value)
    except ValueError:
        # --sort takes an optional value, so a folder written right after it
        # is read as that value.
        hint = (". Put the folder before --sort"
                if os.path.isdir(value) else "")
        raise argparse.ArgumentTypeError(
            f"--sort takes a number of quality tiers "
            f"({MIN_QUALITY_TIERS}..{MAX_QUALITY_TIERS}) or nothing at all, "
            f"got {value!r}{hint}")
    if n < MIN_QUALITY_TIERS:
        raise argparse.ArgumentTypeError(
            f"--sort {n} would put every image in one place, which sorts "
            f"nothing; use at least {MIN_QUALITY_TIERS} tiers, or bare --sort "
            f"for absolute 1-10 scoring")
    if n > MAX_QUALITY_TIERS:
        raise argparse.ArgumentTypeError(
            f"--sort {n} is more tiers than the score has room for; the "
            f"maximum is {MAX_QUALITY_TIERS}")
    return n


def _min_res_arg(value: str) -> int:
    try:
        n = int(value)
    except ValueError:
        raise argparse.ArgumentTypeError(
            f"--min-res takes one number, the side of a square bucket such as "
            f"1024, got {value!r}")
    if n < 0:
        raise argparse.ArgumentTypeError(f"--min-res must be 0 or more, got {n}")
    return n


def _threads_arg(value: str) -> int:
    try:
        n = int(value)
    except ValueError:
        raise argparse.ArgumentTypeError(f"--threads must be an integer, got {value!r}")
    if not 1 <= n <= 32:
        raise argparse.ArgumentTypeError(f"--threads must be 1..32, got {n}")
    return n


