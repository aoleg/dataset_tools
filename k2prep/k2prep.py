# status values
ST_CANDIDATE = "candidate"   # fits a tier; threshold not yet applied
ST_ACCEPTED = "accepted"     # will be / was written
ST_ALREADY = "already"       # output already present, not --force
ST_BELOW = "below"           # composite < threshold
ST_SMALL = "small"           # fits no tier
ST_ERROR = "error"


@dataclass
class Result:
    path: Path
    name: str                     # relpath-qualified under --recursive
    dataset: str = ""             # source dir relative to the root, "" = root
    status: str = ST_CANDIDATE
    error: str = ""

    src_w: int = 0
    src_h: int = 0
    src_ar: float = 0.0

    family: str | None = None
    tier: int | None = None
    bucket: tuple[int, int] | None = None
    crop: tuple[int, int] | None = None
    box: tuple[int, int, int, int] | None = None
    crop_pct: float = 0.0
    r_factor: float = 0.0
    need: int = 0

    q: int | None = None
    q_est: int | None = None
    b: int | None = None
    b_ratio: float = 0.0
    b_unreliable: bool = False
    b_period: float = 0.0
    d: int | None = None
    d_ratio: float = 0.0
    composite: int = 10
    composite_fine: float = 10.0   # composite + position within its band
    no_metrics: bool = False
    scored: bool = False          # two-pass: has the rendered score been taken?
    # The bucket the score was measured at. Kept separate from `bucket` because
    # merging may move the image afterwards, and the cache key must describe
    # what was actually rendered, not where it ended up.
    scored_bucket: tuple[int, int] | None = None

    # --sort
    sort_dest: Path | None = None
    sort_action: str = ""
    sort_tier: int = 0            # 1 = best, in --sort N mode
    sort_dirname: str = ""

    # --copy-to
    reject_reason: str = ""
    copy_dest: Path | None = None
    copy_action: str = ""
    # --copy-to --by-tier: the tier folder the original goes to. Kept apart
    # from `tier`, which stays the 1024 tier the score is taken at.
    dest_tier: int | None = None

    # --vl
    vl_scores: dict[str, int] | None = None
    vl_mean: float | None = None
    vl_error: str = ""

    @property
    def rank_fine(self) -> float:
        """What --sort actually orders on.

        Without --vl this is the technical score. With it, the two are blended -
        and an image the model could not be scored on falls back to its
        technical score for both halves, so a missing opinion is neutral rather
        than silently generous.
        """
        if self.vl_mean is None:
            return self.composite_fine
        return blend_scores(self.vl_mean, self.composite_fine)

    out_stem: str = ""
    out_name: str = ""
    caption_src: Path | None = None
    caption_borrowed: bool = False
    collided: bool = False

    # set when the merge pass moved this image out of its natural bucket
    merged: bool = False

    @property
    def bucket_family(self) -> str:
        """The family of the bucket the image actually sits in, which differs
        from `family` once the merge pass has moved it."""
        if self.tier is None or self.bucket is None:
            return self.family or "-"
        return family_of_bucket(self.tier, self.bucket)


def place(res: Result, tier: int, bucket: tuple[int, int]) -> None:
    """Pin a result to a bucket and recompute every derived geometry field.

    Every assignment goes through here - the initial one in analyse() and the
    merge pass's moves - so a relocated image gets exactly the same crop box it
    would have got had it been assigned there first time.
    """
    bw, bh = bucket
    res.tier = tier
    res.bucket = bucket
    res.crop = crop_dims(res.src_w, res.src_h, bw / bh)
    res.box = crop_box(res.src_w, res.src_h, bw / bh)
    res.need = min_post_crop_area(bucket)
    cw, ch = res.crop
    res.crop_pct = (1.0 - (cw * ch) / (res.src_w * res.src_h)) * 100.0
    res.r_factor = math.sqrt((cw * ch) / (bw * bh))


def _assign(res: Result) -> bool:
    """Family and tier from dimensions alone. False if it fits no tier."""
    if res.src_w < 1 or res.src_h < 1:
        raise ValueError("zero-sized image")
    res.src_ar = res.src_w / res.src_h
    res.family = assign_family(res.src_ar)              # 5.2
    fit = assign_tier(res.src_w, res.src_h, res.family)  # 5.3
    if fit is None:
        smallest = active_tiers()[-1]
        bw, bh = bucket_for(smallest, res.family)
        res.crop = crop_dims(res.src_w, res.src_h, bw / bh)
        res.need = needed_area(smallest, res.family)
        res.status = ST_SMALL
        return False
    place(res, fit[0], fit[1])
    return True


def analyse_geometry(path: Path, dataset: str = "") -> Result:
    """Phase A for two-pass mode: header reads only, no pixels touched."""
    res = Result(path=path, name=qualified_name(dataset, path.name), dataset=dataset)
    try:
        res.src_w, res.src_h, _fmt, _qt = read_geometry(path)
        _assign(res)
    except Exception as exc:
        res.status = ST_ERROR
        res.error = f"{type(exc).__name__}: {exc}"
    return res


def analyse_for_sort(path: Path, dataset: str = "") -> Result:
    """Phase A for --sort and --copy-to: geometry against the 1024 tier only.

    Sorting asks one question - how good would this photograph be if it went
    into training - and that question has a single answer, so it is always asked
    at the 1024 tier. Tier demotion exists to rescue images too small for 1024,
    which is a packing decision, not a quality one; scoring each image at
    whatever tier it happened to fall into would make the scores incomparable
    between folders, which is the opposite of what sorting is for.

    An image already at or below the 1024 tier is scored as it is. Upscaling it
    first would invent detail and flatter the result.
    """
    res = Result(path=path, name=qualified_name(dataset, path.name), dataset=dataset)
    try:
        res.src_w, res.src_h, _fmt, _qt = read_geometry(path)
        if res.src_w < 1 or res.src_h < 1:
            raise ValueError("zero-sized image")
        res.src_ar = res.src_w / res.src_h
        res.family = assign_family(res.src_ar)
        target = bucket_for(SORT_TIER, res.family)
        bw, bh = target
        cw, ch = crop_dims(res.src_w, res.src_h, bw / bh)
        res.crop = (cw, ch)
        res.box = crop_box(res.src_w, res.src_h, bw / bh)
        res.tier = SORT_TIER
        res.bucket = target if cw * ch > bw * bh else (cw, ch)
        res.crop_pct = (1.0 - (cw * ch) / (res.src_w * res.src_h)) * 100.0
        res.r_factor = math.sqrt((cw * ch) / (bw * bh))
    except Exception as exc:
        res.status = ST_ERROR
        res.error = f"{type(exc).__name__}: {exc}"
    return res


def score_rendered(res: Result, resample: int) -> None:
    """Score the image as it will actually reach the trainer.

    Everything here is measured on the rendered pixels, at the bucket the image
    is destined for. Q is still estimated from the source's quantization tables
    because that information exists nowhere else, but it is reported only and
    deliberately kept out of the composite: it describes the source encode, and
    after a 4x downscale that encode's faults are no longer present in the file
    being written. Letting it into a min() composite is precisely what made
    good high-resolution material score 1.
    """
    img, fmt, qtables = load_source(res.path)
    try:
        if res.bucket == res.crop:
            # Already exactly the target size: crop, do not resample. Matters in
            # --sort, where an image at or below the 1024 tier is judged as it is.
            out = img.crop(res.box)
        else:
            out = img.resize(res.bucket, resample=resample, box=res.box)
    finally:
        img.close()
    luma = out.convert("L")
    out.close()
    res.scored_bucket = res.bucket

    res.d_ratio = detail_ratio(luma)
    res.d = score_d_rendered(res.d_ratio)

    if qtables:
        res.q_est = estimate_jpeg_quality(qtables[min(qtables)])
        res.q = score_q(res.q_est)                      # reported, not scored
        # An 8px source block occupies 8 * scale pixels in the output.
        res.b_period = 8.0 * (res.bucket[0] / res.crop[0])
        energy = block_period_energy(luma, res.b_period)
        if energy is not None:
            res.b_ratio = energy
            res.b = score_b_rendered(energy)
    elif fmt in ("PNG", "BMP"):
        res.q_est, res.q = None, 10                     # lossless source

    # B only exists where a JPEG block grid survived the resize; where it did
    # not, that is the answer, and detail carries the score alone.
    scores = [s for s in (res.b, res.d) if s is not None]
    res.composite = min(scores) if scores else 10
    res.no_metrics = not scores

    # floor is monotone, so the fine composite floors to exactly the integer one
    fine = [fine_score(res.d_ratio, D_RENDERED_BANDS, False)] if res.d is not None else []
    if res.b is not None:
        fine.append(fine_score(res.b_ratio, B_RENDERED_BANDS, True))
    res.composite_fine = min(fine) if fine else float(res.composite)
    res.scored = True


def analyse(path: Path, dataset: str = "") -> Result:
    """Phase A for --single-pass: decode and score the source up front."""
    res = Result(path=path, name=qualified_name(dataset, path.name), dataset=dataset)
    try:
        img, fmt, qtables = load_source(path)

        res.src_w, res.src_h = img.size
        if not _assign(res):
            img.close()
            return res

        # 6  metrics, on the source after transpose and RGB conversion
        if fmt in ("PNG", "BMP"):
            res.q_est, res.q = None, 10          # lossless input
        elif qtables:
            res.q_est = estimate_jpeg_quality(qtables[min(qtables)])
            res.q = score_q(res.q_est)
        else:
            res.q_est, res.q = None, None        # unknown encoder, excluded

        luma = _metric_crop(img.convert("L"))
        arr = np.asarray(luma, dtype=np.float32)
        res.b_ratio = blockiness_ratio(arr)
        res.b = score_b(res.b_ratio)
        # The 8px grid no longer aligns if the image was rescaled after being
        # JPEG-encoded, so B reads clean on genuinely damaged material.
        res.b_unreliable = res.q is None and not (res.src_w % 8 == 0 and res.src_h % 8 == 0)
        res.d_ratio = detail_ratio(luma)
        res.d = score_d(res.d_ratio)

        scores = [s for s in (res.q, res.b, res.d) if s is not None]
        if scores:
            res.composite = min(scores)          # minimum, not weighted mean
        else:
            res.composite = 10
            res.no_metrics = True
        res.scored = True

        img.close()
    except Exception as exc:  # one image raising must not kill the run
        res.status = ST_ERROR
        res.error = f"{type(exc).__name__}: {exc}"
    return res


# ---------------------------------------------------------------------------
# Score cache
# ---------------------------------------------------------------------------
#
# Rendered scores cost a decode and a resize each, and they do not depend on
# --threshold at all. The intended workflow is to re-run at a different
# threshold, so without a cache every tuning pass would re-render the whole
# folder to arrive at numbers it already had. Keyed on size and mtime, so an
# edited source is rescored; --force ignores it entirely.

CACHE_FILENAME = "metrics-cache.json"
CACHE_VERSION = 3


def load_score_cache(prep_dir: Path) -> dict:
    path = prep_dir / CACHE_FILENAME
    if not path.is_file():
        return {}
    try:
        doc = json.loads(path.read_text(encoding="utf-8"))
        if doc.get("version") != CACHE_VERSION:
            return {}
        return doc.get("scores", {})
    except Exception:
        return {}                                 # unreadable cache is not fatal


def cache_key(res: Result) -> tuple[int, int, int, int]:
    st = res.path.stat()
    bucket = res.scored_bucket or res.bucket
    return (st.st_size, st.st_mtime_ns, bucket[0], bucket[1])


def apply_cached_score(res: Result, cache: dict) -> bool:
    entry = cache.get(res.name)
    if not entry:
        return False
    res.scored_bucket = res.bucket
    try:
        if list(cache_key(res)) != entry["key"]:
            res.scored_bucket = None
            return False
    except OSError:
        res.scored_bucket = None
        return False
    res.q_est = entry["q_est"]
    res.q = entry["q"]
    res.b = entry["b"]
    res.b_ratio = entry["b_ratio"]
    res.b_period = entry["b_period"]
    res.d = entry["d"]
    res.d_ratio = entry["d_ratio"]
    res.composite = entry["composite"]
    res.composite_fine = entry["composite_fine"]
    res.no_metrics = entry["no_metrics"]
    res.scored = True
    return True


def save_score_cache(prep_dir: Path, results: list[Result], stamp: datetime) -> None:
    scores = {}
    for res in results:
        if not res.scored or res.scored_bucket is None:
            continue
        try:
            key = list(cache_key(res))
        except OSError:
            continue
        scores[res.name] = {
            "key": key, "q_est": res.q_est, "q": res.q,
            "b": res.b, "b_ratio": res.b_ratio, "b_period": res.b_period,
            "d": res.d, "d_ratio": res.d_ratio,
            "composite": res.composite, "composite_fine": res.composite_fine,
            "no_metrics": res.no_metrics,
        }
    doc = {
        "note": "k2prep rendered-image scores, cached so that re-running at a "
                "different --threshold does not re-render the folder. Safe to "
                "delete; it will be rebuilt.",
        "version": CACHE_VERSION,
        "updated": f"{stamp:%Y-%m-%d %H:%M:%S}",
        "scores": scores,
    }
    prep_dir.mkdir(parents=True, exist_ok=True)
    (prep_dir / CACHE_FILENAME).write_text(
        json.dumps(doc, indent=1) + "\n", encoding="utf-8")


