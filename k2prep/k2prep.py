def missing_trainer_message(argv: list[str]) -> str:
    """Why the run stopped, the two options, and the command to copy."""
    def quote(arg: str) -> str:
        # Quoted unless plainly safe, so a path with spaces, "&" or "!" can be
        # pasted back into cmd as it is. Windows paths cannot hold a '"'.
        return arg if re.fullmatch(r"[A-Za-z0-9_.=:+-]+", arg) else f'"{arg}"'

    def example(flag: str) -> str:
        return " ".join(["run.bat"] + [quote(a) for a in list(argv) + [flag]])
    return "\n".join([
        "k2prep resizes the images onto a trainer's bucket sizes, so it needs",
        "to know the trainer. Add one of these options:",
        "",
        f"  --ostris   Ostris AI Toolkit: sides in steps of {OSTRIS_STEP}, which AI Toolkit",
        "             trains as they are, with no second resize or crop.",
        "  --musubi   Musubi Tuner: the sizes of musubi-tuner's bucket list, and a",
        "             dataset.toml for it.",
        "",
        "For example:",
        f"  {example('--ostris')}",
        f"  {example('--musubi')}",
        "",
        "--sort, --copy-to and --move-to keep the originals as they are and do",
        "not need it.",
    ])


BUCKETS_DEFAULT_NOTE = ("the default when the originals are kept as they are; "
                        "--ostris changes it")


def buckets_desc(args) -> str:
    """The bucket set of the run, for the reports."""
    label = active_buckets().label
    if getattr(args, "buckets", None) is None:
        return f"{label} ({BUCKETS_DEFAULT_NOTE})"
    return label


def buckets_notice(args) -> str:
    """The line every run prints before any work."""
    line = f"Using {active_buckets().label} buckets"
    if args.buckets is None:
        line += f" ({BUCKETS_DEFAULT_NOTE})"
    return line


def main(argv=None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    args = parse_args(argv)
    if args.resizes and args.buckets is None:
        print(missing_trainer_message(argv), file=sys.stderr)
        return 2
    # Selected once, before any work: worker threads read it, nothing writes it.
    use_buckets(BUCKET_SETS[args.buckets or MUSUBI.key])
    use_by_tier(args.by_tier)
    print(buckets_notice(args))
    if args.each:
        return run_each(args)
    return run_one(args)


def run_each(args) -> int:
    """-R: one independent run for the folder, then one per first-level
    subfolder, each with its own _prep, reports and TOML.

    This used to live in run.bat, which had to parse the command line to find
    the folder. Delayed expansion, which that parsing needed, deleted every
    '!' in a path, and a folder named "!!!_photos" became "_photos". Here the
    folder is argparse's positional and nothing is re-parsed.

    Folders starting with '_' (k2prep's _prep, cleanup's sidecars) or '.' are
    skipped, and links and junctions are not followed. A folder that fails
    does not stop the sweep.
    """
    root = Path(args.folder).expanduser()
    if not root.is_dir():
        print(f"error: folder does not exist: {root}", file=sys.stderr)
        return 2
    root = root.resolve()
    folders = [root]
    skipped = []
    for entry in sorted(os.scandir(root), key=lambda e: e.name.lower()):
        try:
            if not entry.is_dir():
                continue
        except OSError:
            continue
        if entry.name.startswith(("_", ".")) or _is_link(entry):
            skipped.append(Path(entry.path))
        else:
            folders.append(Path(entry.path))

    failed: list[Path] = []
    for folder in folders:
        print(f"\n=== {folder}")
        one = copy.copy(args)
        one.folder = str(folder)
        one.each = False
        try:
            code = run_one(one)
        except Exception as exc:                  # one folder must not end the sweep
            print(f"error: {type(exc).__name__}: {exc}", file=sys.stderr)
            code = 1
        if code:
            failed.append(folder)
    for folder in skipped:
        print(f"\n=== skipped {folder}")

    print()
    if not failed:
        print(f"All {len(folders)} folder(s) finished.")
        return 0
    print(f"{len(failed)} of {len(folders)} folder(s) failed:")
    for folder in failed:
        print(f"    {folder}")
    return 1


def run_one(args) -> int:
    folder = Path(args.folder).expanduser()
    if not folder.exists():
        print(f"error: folder does not exist: {folder}", file=sys.stderr)
        return 2
    if not folder.is_dir():
        print(f"error: not a directory: {folder}", file=sys.stderr)
        return 2
    folder = folder.resolve()

    target = None
    if args.copy_to is not None:
        target = Path(args.copy_to).expanduser().resolve()
        why = check_copy_target(folder, target)
        if why is None and target.exists() and not target.is_dir():
            why = f"the target exists and is not a directory: {target}"
        if why is not None:
            print(f"error: --copy-to: {why}", file=sys.stderr)
            return 2

    started = datetime.now()
    t0 = time.perf_counter()

    try:
        pairs, unknown, seen_dirs, scan_notes = scan_tree(
            folder, args.recursive, reserved=target is None,
            tier_first_layout=args.by_tier)
    except ScanError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    if not pairs:
        print(f"No images found in {folder} "
              f"({len(unknown)} files with unknown extensions).")
        if not args.recursive:
            try:
                subs = [e for e in os.scandir(folder) if e.is_dir()
                        and not e.name.startswith(("_", "."))]
            except OSError:
                subs = []
            if subs:
                print(f"It has {len(subs)} subfolder(s), and only the files "
                      f"directly in it were scanned. Add --recursive (or "
                      f"--by-tier) to scan the whole tree.")
    if args.recursive:
        n_datasets = len({ds for ds, _p in pairs})
        what = "folder(s)" if target is not None else "dataset(s)"
        scan_notes.append(f"--recursive: {n_datasets} {what} with images "
                          f"across {len(seen_dirs)} folder(s) scanned.")
    for note in scan_notes:
        print(f"note: {note}")

    prep_dir = folder / PREP_DIRNAME
    reports_dir = prep_dir / REPORTS_DIRNAME
    ext = ".png" if args.png else ".jpg"
    resample = RESAMPLE_FILTERS[args.filter]

    if args.sort is not None:
        return run_sort(args, folder, prep_dir, reports_dir,
                        [p for _ds, p in pairs], unknown, resample, started, t0)
    if target is not None:
        return run_copy(args, folder, target, prep_dir, reports_dir, pairs,
                        unknown, scan_notes, resample, started, t0)

    # -- phase A: geometry (and, in single-pass mode, source scores) ---------
    # Two-pass mode reads headers only here: nothing is decoded until there is
    # a bucket to render into.
    worker = analyse if args.single_pass else analyse_geometry
    results: list[Result] = []
    if pairs:
        with ThreadPoolExecutor(max_workers=args.local_threads) as pool:
            futures = [pool.submit(worker, p, ds) for ds, p in pairs]
            for fut in tqdm(as_completed(futures), total=len(futures),
                            desc="analysing" if args.single_pass else "scanning ",
                            unit="img"):
                results.append(fut.result())
    # Report ordering is by dataset then filename, not completion order.
    results.sort(key=lambda r: (r.dataset, r.name))
    for r in results:
        if r.status == ST_CANDIDATE:
            r.caption_src = caption_for(r.path)

    # -- preliminary report: the natural, unmerged assignment ----------------
    # Written before merging is decided and, in two-pass mode, before anything
    # is scored - so the bucket distribution it shows is the raw one, the
    # problem the merge pass exists to fix. Diff it against the final report to
    # see exactly what moved and what the rendered scores turned out to be.
    reports_dir.mkdir(parents=True, exist_ok=True)
    kind = "scan" if args.report else "process"
    stamp = f"{started:%Y%m%d-%H%M%S}"
    candidates = [r for r in results if r.status == ST_CANDIDATE]
    resolve_names(candidates, ext)
    prelim_path = _free_path(reports_dir, f"{kind}-{stamp}-preliminary", ".txt")
    prelim_path.write_text(
        build_report(args, folder, results, unknown, [], started, datetime.now(),
                     time.perf_counter() - t0, list(scan_notes), STAGE_PRELIMINARY),
        encoding="utf-8",
    )

    # -- phase S: render every candidate and score the result -----------------
    # The whole point of the default mode. Nothing is saved here; the rendered
    # image exists only long enough to be measured, so images that fail the
    # threshold are never written to disk at all.
    cache_hits = 0
    if not args.single_pass and candidates:
        cache = {} if args.force else load_score_cache(prep_dir)
        todo = []
        for r in candidates:
            if apply_cached_score(r, cache):
                cache_hits += 1
            else:
                todo.append(r)
        if todo:
            with ThreadPoolExecutor(max_workers=args.local_threads) as pool:
                futures = {pool.submit(score_rendered, r, resample): r for r in todo}
                for fut in tqdm(as_completed(futures), total=len(futures),
                                desc="scoring  ", unit="img"):
                    r = futures[fut]
                    try:
                        fut.result()
                    except Exception as exc:
                        r.status = ST_ERROR
                        r.error = f"{type(exc).__name__}: {exc}"

    # -- threshold, on whichever score was taken -----------------------------
    for r in results:
        if r.status == ST_CANDIDATE:
            r.status = ST_BELOW if r.composite < args.threshold else ST_ACCEPTED
    accepted = [r for r in results if r.status == ST_ACCEPTED]

    # -- merge: consolidate undersized buckets before writing anything -------
    # Per dataset, never across: each _prep/<dataset>/<tier> is its own
    # [[datasets]] block and musubi forms batches within a dataset only, so a
    # bucket in one dataset can never pad out an undersized one in another.
    # The exception is --ostris --by-tier, where AI Toolkit trains a whole
    # _<tier> folder as one dataset: there the pool is the tier (merge_pooled).
    moves: list[Move] = []
    unmerged: list[tuple[Result, str]] = []
    if not args.no_merge and accepted:
        pools = ([accepted] if merge_pooled() else
                 [[r for r in accepted if r.dataset == ds]
                  for ds in sorted({r.dataset for r in accepted})])
        for pool in pools:
            m, u, _before, _after = plan_merge(pool)
            moves.extend(m)
            unmerged.extend(u)

    # Names are resolved after merging, because collisions are per tier folder
    # and merging can move an image into a different tier.
    for r in results:
        r.out_stem = ""
        r.out_name = ""
        r.collided = False
        r.caption_borrowed = False
    collisions = resolve_names(accepted, ext)

    planned: dict[tuple[str, int], set[str]] = defaultdict(set)
    for r in accepted:
        planned[(r.dataset, r.tier)].add(r.out_name)
        if r.caption_src is not None:
            planned[(r.dataset, r.tier)].add(f"{r.out_stem}.txt")

    if not args.force:
        for r in accepted:
            if already_correct(tier_dir(prep_dir, r.dataset, r.tier) / r.out_name,
                               r.bucket):
                r.status = ST_ALREADY

    removed = sweep_superseded(prep_dir, seen_dirs, planned, dry_run=args.report)
    to_write = [r for r in results if r.status == ST_ACCEPTED]

    # -- phase C: parallel write ---------------------------------------------
    if not args.report and to_write:
        for ds, tier in sorted({(r.dataset, r.tier) for r in to_write}):
            tier_dir(prep_dir, ds, tier).mkdir(parents=True, exist_ok=True)
        with ThreadPoolExecutor(max_workers=args.local_threads) as pool:
            futures = {
                pool.submit(write_output, r,
                            tier_dir(prep_dir, r.dataset, r.tier), resample, ext): r
                for r in to_write
            }
            for fut in tqdm(as_completed(futures), total=len(futures),
                            desc="writing  ", unit="img"):
                r = futures[fut]
                try:
                    fut.result()
                except Exception as exc:
                    r.status = ST_ERROR
                    r.error = f"{type(exc).__name__}: {exc}"

    elapsed = time.perf_counter() - t0
    finished = datetime.now()

    notes: list[str] = list(scan_notes)
    if args.recursive:
        for ds in find_stale_datasets(prep_dir, seen_dirs):
            notes.append(f"stale output folder {PREP_DIRNAME}/{ds} has no "
                         f"matching source folder this run; left alone, and "
                         f"not referenced by the TOML. Delete it by hand if "
                         f"it is unwanted.")
    smallest = active_tiers()[-1]
    if tier_first() and any(r.tier == smallest for r in results
                            if r.status in (ST_ACCEPTED, ST_ALREADY)):
        notes.append(f"the {smallest} tier is for completeness: its scores are "
                     f"less reliable, because the quality bands were fitted on "
                     f"larger renders. Keep or delete "
                     f"{PREP_DIRNAME}/{by_tier_dirname(smallest)} by hand.")
    if not args.single_pass and candidates:
        # Written in dry runs too: it costs nothing and makes the recommended
        # "--report first, then run for real" workflow skip a second rendering
        # pass over the whole folder.
        save_score_cache(prep_dir, results, finished)
        notes.append(f"rendered scores cached in {CACHE_FILENAME} "
                     f"({cache_hits} of {len(candidates)} reused this run). "
                     "Delete it to force a rescore.")

    # -- toml, written every run ---------------------------------------------
    toml_path = None
    if active_buckets() is not MUSUBI:
        # The TOML is musubi-tuner's. One left by an earlier --musubi run would
        # point musubi at renders sized for another trainer, so it goes.
        notes.append(f"{TOML_FILENAME} not written: it is for musubi-tuner, and "
                     f"this run uses {active_buckets().label} buckets.")
        for name in remove_own_toml(prep_dir, dry_run=args.report):
            notes.append(f"{name} from an earlier --musubi run "
                         f"{'would be' if args.report else 'was'} removed: it "
                         f"pointed musubi-tuner at these folders.")
    elif args.report:
        notes.append(f"{TOML_FILENAME} not written: a dry run creates no tier "
                     "folders for it to point at.")
    else:
        toml_path = emit_toml(prep_dir, finished, seen_dirs)
        if toml_path is None:
            notes.append(f"{TOML_FILENAME} not written, no tier folder has images.")
        elif toml_path.name != TOML_FILENAME:
            notes.append(f"{TOML_FILENAME} exists and was not written by k2prep, "
                         f"so it was left alone and {toml_path.name} written instead.")
    for note in notes[len(scan_notes):]:      # scan notes were printed up front
        print(f"note: {note}")

    # -- final report ---------------------------------------------------------
    report_path = _free_path(reports_dir, f"{kind}-{stamp}-final", ".txt")
    report_path.write_text(
        build_report(args, folder, results, unknown, collisions,
                     started, finished, elapsed, notes, STAGE_FINAL,
                     moves, unmerged, removed),
        encoding="utf-8",
    )

    # -- console summary ------------------------------------------------------
    counts = defaultdict(int)
    for r in results:
        counts[r.status] += 1
    by_tier = defaultdict(int)
    for r in results:
        if r.status in (ST_ACCEPTED, ST_ALREADY):
            by_tier[r.tier] += 1
    # Undersized is judged per merge pool: per dataset, or per tier when the
    # whole tier folder is one pool (merge_pooled).
    per_ds_bucket: dict[tuple[str, int, tuple[int, int]], int] = defaultdict(int)
    for r in results:
        if r.status in (ST_ACCEPTED, ST_ALREADY):
            pool = "" if merge_pooled() else r.dataset
            per_ds_bucket[(pool, r.tier, r.bucket)] += 1
    undersized = sum(1 for n in per_ds_bucket.values()
                     if 0 < n < MIN_BUCKET_SIZE)

    print()
    print(f"k2prep {'scan' if args.report else 'run'}: {len(results)} images "
          f"in {_hms(elapsed)}")
    if args.recursive:
        print(f"  datasets    {len({r.dataset for r in results}):>7}")
    for tier in active_tiers():
        if by_tier[tier]:
            label = by_tier_dirname(tier) if tier_first() else f"tier {tier}"
            print(f"  {label:<11} {by_tier[tier]:>7}")
    print(f"  written     {counts[ST_ACCEPTED]:>7}"
          f"{'  (dry run: nothing written)' if args.report else ''}")
    print(f"  already     {counts[ST_ALREADY]:>7}")
    print(f"  below thr.  {counts[ST_BELOW]:>7}")
    print(f"  too small   {counts[ST_SMALL]:>7}")
    print(f"  errors      {counts[ST_ERROR]:>7}")
    if unknown:
        print(f"  unknown ext {len(unknown):>7}")
    if not args.no_merge:
        print(f"  merged      {len(moves):>7}   "
              f"({undersized} bucket(s) still under {MIN_BUCKET_SIZE})")
    if removed:
        print(f"  superseded  {len(removed):>7}"
              f"{'  (dry run: nothing removed)' if args.report else '  removed'}")
    print(f"  reports     {prelim_path.name}")
    print(f"              {report_path.name}")
    print(f"              in {reports_dir}")
    if toml_path is not None:
        print(f"  toml        {toml_path}")

    return 0


if __name__ == "__main__":
    sys.exit(main())
