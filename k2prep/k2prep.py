def run_sort(args, folder: Path, prep_dir: Path, reports_dir: Path,
             images: list[Path], unknown: list[str], resample: int,
             started: datetime, t0: float) -> int:
    """Triage a folder by quality. Builds no dataset: no tier folders, no TOML.

    Kept separate from the dataset pipeline on purpose. Under --move the source
    images leave the folder, which would pull the rug from under a tier build
    running in the same pass - the next run would find no sources and sweep the
    tier folders empty.
    """
    # The endpoint is checked before a single image is opened: a typo in .env
    # or a server that is not running should cost a sentence, not a long wait.
    vl_cfg = None
    if args.vl_criteria:
        try:
            vl_cfg = load_vl_config(args.vl_criteria)
            loaded = vl_preflight(vl_cfg)
        except VLUnavailable as exc:
            print(f"error: --vl unavailable: {exc}", file=sys.stderr)
            return 2
        print(f"--vl endpoint {vl_cfg.endpoint}  model {vl_cfg.model}  "
              f"[server reports: {loaded}]")
        print(f"     criteria: {', '.join(vl_cfg.criteria)}")

    notes: list[str] = []
    for flag, why in (("threshold", "nothing is rejected when sorting; every "
                                    "image goes to the folder for its score"),
                      ("png", "originals are placed verbatim, so the output "
                              "format option does not apply"),
                      ("single_pass", f"sorting always scores the rendered "
                                      f"{SORT_TIER}-tier image, which is what "
                                      f"the score means"),
                      ("no_merge", "sorting does not use buckets")):
        value = getattr(args, flag, None)
        if value:
            notes.append(f"--{flag.replace('_', '-')} ignored: {why}.")

    results: list[Result] = []
    if images:
        with ThreadPoolExecutor(max_workers=args.local_threads) as pool:
            futures = [pool.submit(analyse_for_sort, p) for p in images]
            for fut in tqdm(as_completed(futures), total=len(futures),
                            desc="scanning ", unit="img"):
                results.append(fut.result())
    results.sort(key=lambda r: r.name)
    for r in results:
        if r.status == ST_CANDIDATE:
            r.caption_src = caption_for(r.path)

    # -- score, at the 1024 tier, with the same cache the dataset run uses ----
    todo = [r for r in results if r.status == ST_CANDIDATE]
    cache_hits = 0
    if todo:
        cache = {} if args.force else load_score_cache(prep_dir)
        pending = []
        for r in todo:
            if apply_cached_score(r, cache):
                cache_hits += 1
            else:
                pending.append(r)
        if pending:
            with ThreadPoolExecutor(max_workers=args.local_threads) as pool:
                futures = {pool.submit(score_rendered, r, resample): r
                           for r in pending}
                for fut in tqdm(as_completed(futures), total=len(futures),
                                desc="scoring  ", unit="img"):
                    r = futures[fut]
                    try:
                        fut.result()
                    except Exception as exc:
                        r.status = ST_ERROR
                        r.error = f"{type(exc).__name__}: {exc}"

    scored = [r for r in results if r.scored]
    if todo:
        save_score_cache(prep_dir, results, datetime.now())
        notes.append(f"scores cached in {CACHE_FILENAME} "
                     f"({cache_hits} of {len(todo)} reused this run).")

    # -- preliminary report: the scores, before any decision about tiers -----
    reports_dir.mkdir(parents=True, exist_ok=True)
    stamp = f"{started:%Y%m%d-%H%M%S}"
    prelim_path = _free_path(reports_dir, f"sort-{stamp}-preliminary", ".txt")
    prelim_path.write_text(
        build_sort_report(args, folder, results, unknown, [], started,
                          datetime.now(), time.perf_counter() - t0, notes,
                          STAGE_PRELIMINARY, [], None),
        encoding="utf-8",
    )

    # -- ask the model, after the preliminary report is safely on disk -------
    # Deliberately last: it is the slow, fallible, non-reproducible half, and if
    # it dies halfway the technical scores are already written and cached.
    if vl_cfg is not None and scored:
        vl_cache = {} if args.force else load_vl_cache(prep_dir, vl_cfg.signature())
        pending = [r for r in scored
                   if not apply_cached_vl(r, vl_cache, vl_cfg.criteria)]
        vl_hits = len(scored) - len(pending)
        consecutive = 0
        abandoned = False
        if pending:
            with ThreadPoolExecutor(max_workers=args.vl_threads) as pool:
                futures = {pool.submit(vl_score_image, r, vl_cfg, resample): r
                           for r in pending}
                for fut in tqdm(as_completed(futures), total=len(futures),
                                desc="asking   ", unit="img"):
                    r = futures[fut]
                    if abandoned:
                        fut.cancel()
                        continue
                    try:
                        r.vl_scores = fut.result()
                        r.vl_mean = statistics.fmean(r.vl_scores.values())
                        consecutive = 0
                    except Exception as exc:
                        r.vl_error = f"{type(exc).__name__}: {exc}"
                        consecutive += 1
                        if consecutive >= VL_GIVE_UP_AFTER:
                            abandoned = True
        save_vl_cache(prep_dir, vl_cfg, results, datetime.now())
        graded = sum(1 for r in scored if r.vl_mean is not None)
        notes.append(f"model graded {graded} of {len(scored)} images "
                     f"({vl_hits} reused from {VL_CACHE_FILENAME}).")
        if abandoned:
            notes.append(f"gave up on the model after {VL_GIVE_UP_AFTER} "
                         f"failures in a row; the rest are ranked on their "
                         f"technical score alone.")
        elif graded < len(scored):
            notes.append("images the model could not grade fall back to their "
                         "technical score, which is neither a reward nor a "
                         "penalty.")

    # -- decide where each image goes ----------------------------------------
    tiers: list[QualityTier] = []
    if args.sort == SORT_ABSOLUTE:
        for r in scored:
            r.sort_tier = r.composite
            r.sort_dirname = f"{SORT_DIR_PREFIX}{r.composite}"
    else:
        tiers = plan_quality_tiers(scored, args.sort)
        empty = [t.name for t in tiers if t.count == 0]
        if empty:
            notes.append(f"only {len(scored)} images to divide, so "
                         f"{', '.join(empty)} came out empty.")
        tied = [t.name for t in tiers if t.tied_break]
        if tied:
            notes.append("a tier break fell between images of identical "
                         f"quality ({', '.join(tied)}); the split there is "
                         "arbitrary.")

    # -- place, sequentially: moving files is not worth parallelising ---------
    for r in results:
        if r.scored and r.status != ST_ERROR and r.sort_dirname:
            place_sorted(r, prep_dir, args.move, args.force, args.report)
    stale = find_stale_sorted(prep_dir, results)

    elapsed = time.perf_counter() - t0
    finished = datetime.now()
    for note in notes:
        print(f"note: {note}")

    report_path = _free_path(reports_dir, f"sort-{stamp}-final", ".txt")
    report_path.write_text(
        build_sort_report(args, folder, results, unknown, stale,
                          started, finished, elapsed, notes, STAGE_FINAL,
                          tiers, vl_cfg),
        encoding="utf-8",
    )

    counts = defaultdict(int)
    for r in results:
        counts[r.sort_action] += 1
    errors = sum(1 for r in results
                 if r.status == ST_ERROR or r.sort_action == SORT_FAILED)

    print()
    print(f"k2prep sort{' (dry run)' if args.report else ''}: "
          f"{len(results)} images in {_hms(elapsed)}")
    if tiers:
        for tier in tiers:
            print(f"  {tier.name:<10} {tier.count:>7}"
                  f"   {'score ' + _score_span(tier) if tier.count else ''}")
    else:
        hist = defaultdict(int)
        for r in scored:
            hist[r.composite] += 1
        for score in range(10, 0, -1):
            if hist[score]:
                print(f"  {SORT_DIR_PREFIX}{score:<6} {hist[score]:>7}")
    verb = "moved " if args.move else "copied"
    print(f"  {verb}      {counts[SORT_COPIED] + counts[SORT_MOVED]:>7}"
          f"{'  (dry run: nothing placed)' if args.report else ''}")
    print(f"  in place    {counts[SORT_PRESENT]:>7}")
    print(f"  errors      {errors:>7}")
    if unknown:
        print(f"  unknown ext {len(unknown):>7}")
    if stale:
        print(f"  duplicates  {len(stale):>7}   (in other score folders, left alone)")
    print(f"  report      {report_path}")
    return 0


