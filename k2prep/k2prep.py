def scan_folder(folder: Path) -> tuple[list[Path], list[str]]:
    """One directory, files only. Returns (image paths sorted by filename,
    unknown-extension filenames sorted)."""
    images: list[Path] = []
    unknown: list[str] = []
    for entry in os.scandir(folder):
        if entry.is_dir():
            continue                              # includes _prep/
        name = entry.name
        ext = os.path.splitext(name)[1]
        if ext in KNOWN_EXTENSIONS:
            images.append(Path(entry.path))
        elif ext.lower() != ".txt":
            unknown.append(name)
    images.sort(key=lambda p: p.name)
    unknown.sort()
    return images, unknown


def qualified_name(dataset: str, name: str) -> str:
    """Display / cache-key name: relpath-qualified under --recursive, bare at
    the root - so a non-recursive run's cache entries and reports look exactly
    as they always did."""
    return f"{dataset}/{name}" if dataset else name


def dataset_dir(prep_dir: Path, dataset: str) -> Path:
    """_prep/<relpath>, mirroring the source tree; the root maps to _prep
    itself, so a tree with no subfolders produces the flat layout unchanged."""
    return prep_dir / dataset if dataset else prep_dir


def tier_dir(prep_dir: Path, dataset: str, tier: int,
             tier_first_layout: bool | None = None) -> Path:
    """Where a dataset's renders for one tier go.

    _prep/<relpath>/<tier>/ normally; under --by-tier _prep/_<tier>/<relpath>/,
    one folder per tier holding the whole tree. The run's layout unless one is
    named, which the sweep does to clear the other layout's outputs.
    """
    if tier_first_layout is None:
        tier_first_layout = _tier_first
    if tier_first_layout:
        base = prep_dir / by_tier_dirname(tier)
        return base / dataset if dataset else base
    return dataset_dir(prep_dir, dataset) / str(tier)


def _is_link(entry: os.DirEntry) -> bool:
    """A symlink or a Windows junction: anything that points elsewhere.

    is_dir(follow_symlinks=False) is not enough - Windows reports a junction as
    a real directory there - so ask for the reparse tag, which is non-zero for
    every kind of reparse point. Anything that cannot be classified is treated
    as a link, since the safe direction is not following it.
    """
    try:
        if entry.is_symlink():
            return True
        st = entry.stat(follow_symlinks=False)
    except OSError:
        return True
    return getattr(st, "st_reparse_tag", 0) != 0


class ScanError(RuntimeError):
    """The source tree cannot be mirrored into _prep. Raised before any work."""


def scan_tree(root: Path, recursive: bool, reserved: bool = True,
              tier_first_layout: bool = False):
    """The scanner. A dataset is any directory that directly contains at least
    one image; its images are only the files directly in it, so each source
    directory maps 1:1 to _prep/<relpath>/<tier>/ and pooling a subtree is the
    user's call, made by flattening the source.

    Returns (images, unknown, dirs, notes):
      images  - sorted list of (dataset relpath, path)
      unknown - relpath-qualified unknown-extension names, sorted
      dirs    - every directory visited (relpath, root = ""), sorted; this is
                what sweeping and TOML emission iterate, so a dataset whose
                images all vanished still gets its stale outputs cleared
      notes   - report lines about skipped links and unreadable directories

    Directories whose name starts with "_" or "." are skipped at every depth.
    The underscore rule is what keeps a nested _prep left by an earlier
    per-folder run (-R) from being ingested as source - those hold
    already-cropped renders of the same photographs. Directory links and
    junctions are never followed: a junction cycle would loop forever and one
    pointing outside the tree would drag foreign folders in.

    A source directory named like a tier ("1024") would make _prep/<x>/1024
    ambiguous - dataset or tier folder - and "reports" at the first level would
    collide with _prep/reports. Both raise ScanError; rename the folder.
    reserved=False drops both checks, for --copy-to, which mirrors the tree
    into its own target rather than into _prep.

    The tier-first layout of --by-tier (_prep/_<tier>/<relpath>/) has neither
    collision. Its one is "cache" at the first level: the root's tier folder
    _prep/_1024 holds musubi's cache folder of that name, and a dataset there
    would mix its renders with the root's cache files.
    """
    if not recursive:
        images, unknown = scan_folder(root)
        return [("", p) for p in images], unknown, [""], []

    tier_names = {str(t) for t in TIERS}
    out_images: list[tuple[str, Path]] = []
    out_unknown: list[str] = []
    dirs: list[str] = []
    notes: list[str] = []
    skipped = 0
    visited: set[str] = set()

    def walk(directory: Path, rel: str) -> None:
        nonlocal skipped
        try:
            real = os.path.normcase(str(directory.resolve()))
        except OSError as exc:
            notes.append(f"cannot resolve {rel or root}: {exc}")
            return
        if real in visited:                      # junction/symlink cycle backstop
            return
        visited.add(real)
        try:
            entries = sorted(os.scandir(directory), key=lambda e: e.name)
        except OSError as exc:
            notes.append(f"cannot read {rel or root}: {exc}")
            return
        dirs.append(rel)
        subdirs: list[tuple[Path, str]] = []
        for entry in entries:
            name = entry.name
            relname = qualified_name(rel, name)
            try:
                is_dir = entry.is_dir()
            except OSError:
                continue
            if is_dir:
                if name.startswith(("_", ".")):
                    skipped += 1
                    continue
                if _is_link(entry):
                    notes.append(f"skipped {relname}: directory links and "
                                 f"junctions are not followed")
                    continue
                low = name.lower()
                if reserved and tier_first_layout:
                    if rel == "" and low == CACHE_DIRNAME:
                        raise ScanError(
                            f"source folder {relname!r} would collide with "
                            f"musubi's cache folder in "
                            f"{PREP_DIRNAME}/{by_tier_dirname(TIERS[0])}. "
                            f"Rename it, or run without --by-tier.")
                elif reserved and low in tier_names:
                    raise ScanError(
                        f"source folder {relname!r} is named like a k2prep tier "
                        f"folder, which makes _prep/{relname} ambiguous. Rename "
                        f"it, or run without --recursive.")
                if (reserved and not tier_first_layout and rel == ""
                        and low == REPORTS_DIRNAME):
                    raise ScanError(
                        f"source folder {relname!r} would collide with "
                        f"_prep/{REPORTS_DIRNAME}. Rename it, or run without "
                        f"--recursive.")
                subdirs.append((Path(entry.path), relname))
                continue
            ext = os.path.splitext(name)[1]
            if ext in KNOWN_EXTENSIONS:
                out_images.append((rel, Path(entry.path)))
            elif ext.lower() != ".txt":
                out_unknown.append(relname)
        for sub, relname in subdirs:
            walk(sub, relname)

    walk(root, "")
    if skipped:
        notes.append(f"skipped {skipped} folder(s) starting with '_' or '.'")
    out_images.sort(key=lambda dp: (dp[0], dp[1].name))
    out_unknown.sort()
    dirs.sort()
    return out_images, out_unknown, dirs, notes


def caption_for(path: Path) -> Path | None:
    cap = path.parent / f"{path.stem}.txt"
    return cap if cap.is_file() else None


def _free_path(directory: Path, stem: str, ext: str) -> Path:
    """First unused <stem><ext>, <stem>-2<ext>, ... Reports are never
    overwritten."""
    path = directory / f"{stem}{ext}"
    n = 1
    while path.exists():
        n += 1
        path = directory / f"{stem}-{n}{ext}"
    return path


# ---------------------------------------------------------------------------
# --sort: file placement
# ---------------------------------------------------------------------------
#
# The one place in k2prep that can remove something from the source folder, and
# only under --move, which exists for exactly that purpose. Everything else in
# this program treats the input folder as read-only and that has not changed.
#
# Ordering is deliberate: the destination is written first and only then is the
# source unlinked, so an interrupted run leaves a duplicate rather than a hole.
# shutil.move does this already (rename within a volume, copy-then-unlink
# across one); it is used rather than hand-rolled so the same-volume case stays
# atomic.

SORT_COPIED = "copied"
SORT_MOVED = "moved"
SORT_PRESENT = "already there"
SORT_FAILED = "failed"


def sort_dir_for(prep_dir: Path, score: int) -> Path:
    return prep_dir / f"{SORT_DIR_PREFIX}{score}"


# ---------------------------------------------------------------------------
# --sort N: dynamic quality tiers
# ---------------------------------------------------------------------------
#
# Absolute bands answer "how good is this image". Asked to fill N tiers, the
# question changes to "how good is this image *for this folder*", and the two
# want different machinery. A folder of uniformly excellent photographs has a
# best third and a worst third just as much as a mixed one does, and telling
# the user their 400 images are all quality1 is useless for triage.
#
# So tiers are cut by rank, not by value. Rank alone would split ties
# arbitrarily and ignore real structure in the data, so each cut is allowed to
# slide within a window around its ideal position and settle on the largest gap
# it can find there. Balanced where the data is smooth, natural where it is
# clustered.
#
# The window is what stops a couple of outliers from defining a tier. A pure
# natural-breaks fit would happily give two exceptional images a tier of their
# own and push everything else down a grade, which is exactly the failure the
# absolute bands already have.

QUALITY_DIR_PREFIX = "quality"
SORT_ABSOLUTE = -1              # sentinel: --sort given with no number
MIN_QUALITY_TIERS = 2
MAX_QUALITY_TIERS = 10

# How far a cut may slide from its ideal position, as a fraction of one tier's
# width, while hunting for a natural break.
QUALITY_CUT_WINDOW = 0.35


# ---------------------------------------------------------------------------
# --vl: scoring against user criteria with a local vision-language model
# ---------------------------------------------------------------------------
#
# What this is for: the B and D metrics measure whether an image is technically
# sound, and they are the only thing here that can. What they cannot do is look
# at a photograph and say whether it is well composed, whether the subject is
# the thing you wanted, or whether it is a screenshot of a menu. A VL model can,
# and it is hopeless at the reverse - a vision projector runs at a few hundred
# pixels, which is exactly where JPEG blocking and fine detail have already been
# thrown away. The two are complementary, so both are kept and neither is
# allowed to stand in for the other.
#
# LOCAL ENDPOINTS ONLY, and no authentication is ever sent. That is deliberate:
# no key to leak, no bill to run up, no folder of photographs leaving the
# machine by accident. A remote endpoint will reject an unauthenticated request
# on its own, which is the intended outcome.
#
# A --vl run is NOT reproducible. Even at temperature 0 a server can return
# different text between runs, and a different model will disagree entirely.
# The report says so. Everything else in k2prep remains deterministic, and the
# technical score is always reported alongside so it can be checked.

VL_ENV_FILENAME = ".env"
VL_SAMPLE_ENV = "sample.env"
VL_CACHE_FILENAME = "vl-cache.json"
VL_PROMPT_VERSION = 1

VL_ENV_ENDPOINT = "K2PREP_VL_ENDPOINT"
VL_ENV_MODEL = "K2PREP_VL_MODEL"
VL_ENV_TIMEOUT = "K2PREP_VL_TIMEOUT"

VL_MAX_CRITERIA = 8
VL_MAX_EDGE = 512          # the projector downsamples anyway; sending more is
                           # upload for nothing
VL_JPEG_QUALITY = 85
VL_RETRIES = 3
VL_GIVE_UP_AFTER = 5       # consecutive hard failures before abandoning the pass

# How much the model's opinion counts against the measured technical score, as
# the exponent in a weighted geometric mean. Higher than the technical half,
# because it answers the question the user actually asked - but a geometric mean
# means a genuinely broken image cannot be rescued by a perfect critique, which
# a weighted average would allow. At 0.65: a perfect-criteria, technically awful
# image (10, 2) lands at 5.7, below a merely good one at (7, 7) = 7.0, while a
# technically perfect image that ignores the criteria (2, 10) lands at 3.5.
VL_WEIGHT = 0.65


@dataclass
class VLConfig:
    endpoint: str
    model: str
    timeout: float
    criteria: list[str]

    @property
    def chat_url(self) -> str:
        return f"{self.endpoint}/chat/completions"

    @property
    def models_url(self) -> str:
        return f"{self.endpoint}/models"

    def signature(self) -> str:
        """Cache identity: change the model, the criteria or the prompt and the
        cached opinions are no longer about the same question."""
        raw = json.dumps({"v": VL_PROMPT_VERSION, "model": self.model,
                          "criteria": self.criteria, "edge": VL_MAX_EDGE},
                         sort_keys=True)
        return hashlib.sha256(raw.encode("utf-8")).hexdigest()[:16]


class VLUnavailable(RuntimeError):
    """The endpoint cannot be used. Raised before any work is done."""


def parse_env_file(path: Path) -> dict[str, str]:
    """Minimal KEY=VALUE reader. No dependencies, no interpolation, no export."""
    env: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        value = value.strip().strip('"').strip("'")
        if value:
            env[key.strip()] = value
    return env


def load_vl_config(criteria: list[str]) -> VLConfig:
    """Read .env from beside the script, then the working directory.

    Every failure here is a clear sentence about what to do next: this runs
    before any images are touched, so there is no half-finished state to
    explain.
    """
    here = Path(__file__).resolve().parent
    looked = list(dict.fromkeys([here, Path.cwd().resolve()]))
    env: dict[str, str] = {}
    found = None
    for path in [d / VL_ENV_FILENAME for d in looked]:
        if path.is_file():
            try:
                env = parse_env_file(path)
            except OSError as exc:
                raise VLUnavailable(f"cannot read {path}: {exc}") from exc
            found = path
            break
    if found is None:
        where = " or ".join(str(d) for d in looked)
        raise VLUnavailable(
            f"--vl needs a {VL_ENV_FILENAME} naming your local endpoint, and "
            f"none was found in {where}. Copy {VL_SAMPLE_ENV} to "
            f"{VL_ENV_FILENAME} and edit it.")

    endpoint = env.get(VL_ENV_ENDPOINT, "").strip().rstrip("/")
    if not endpoint:
        raise VLUnavailable(
            f"{found} does not set {VL_ENV_ENDPOINT}. See {VL_SAMPLE_ENV} for "
            f"the endpoint each of llama.cpp, koboldcpp and LM Studio uses.")
    if not endpoint.startswith(("http://", "https://")):
        raise VLUnavailable(
            f"{VL_ENV_ENDPOINT} must start with http:// or https://, got "
            f"{endpoint!r}")
    if not endpoint.endswith("/v1"):
        endpoint = f"{endpoint}/v1"

    try:
        timeout = float(env.get(VL_ENV_TIMEOUT, "120"))
    except ValueError:
        raise VLUnavailable(f"{VL_ENV_TIMEOUT} in {found} is not a number")

    return VLConfig(endpoint=endpoint,
                    model=env.get(VL_ENV_MODEL, "local-model").strip(),
                    timeout=max(1.0, timeout),
                    criteria=criteria)


def _http_json(url: str, timeout: float, payload: dict | None = None) -> dict:
    data = json.dumps(payload).encode("utf-8") if payload is not None else None
    req = urllib.request.Request(
        url, data=data,
        headers={"Content-Type": "application/json", "Accept": "application/json"},
        method="POST" if data else "GET")
    # No Authorization header, ever. See the note at the top of this section.
    with urllib.request.urlopen(req, timeout=timeout) as resp:
        return json.loads(resp.read().decode("utf-8"))


def vl_preflight(cfg: VLConfig) -> str:
    """One request before the run, so a dead server fails in a sentence rather
    than as several thousand timeouts."""
    try:
        doc = _http_json(cfg.models_url, timeout=min(cfg.timeout, 15.0))
    except urllib.error.HTTPError as exc:
        if exc.code in (401, 403):
            raise VLUnavailable(
                f"{cfg.endpoint} demands authentication. k2prep deliberately "
                f"sends no key and supports local servers only.") from exc
        raise VLUnavailable(f"{cfg.endpoint} answered HTTP {exc.code}") from exc
    except urllib.error.URLError as exc:
        raise VLUnavailable(
            f"cannot reach {cfg.endpoint}: {exc.reason}. Is the server "
            f"running, and does it have a vision model loaded?") from exc
    except Exception as exc:
        raise VLUnavailable(f"cannot reach {cfg.endpoint}: {exc}") from exc
    names = [m.get("id", "?") for m in doc.get("data", []) if isinstance(m, dict)]
    return ", ".join(names[:4]) if names else "(server named no model)"


def build_vl_messages(cfg: VLConfig, image_b64: str) -> list[dict]:
    lines = [
        "Rate this photograph on each criterion below, from 1 to 10.",
        "10 is excellent, 1 is unusable. Use the whole range.",
        "",
        "  10  could not be better on this criterion",
        "   7  good, with minor faults",
        "   5  acceptable but clearly flawed",
        "   3  poor; would hurt a training set",
        "   1  unusable",
        "",
        "Criteria:",
    ]
    lines += [f"  - {c}" for c in cfg.criteria]
    lines += [
        "",
        "Reply with one JSON object mapping each criterion to its integer "
        "score, and nothing else.",
        "Example: {" + ", ".join(f'"{c}": 7' for c in cfg.criteria) + "}",
    ]
    return [
        {"role": "system",
         "content": "You grade photographs for a training dataset. "
                    "You reply with JSON and no commentary."},
        {"role": "user", "content": [
            {"type": "text", "text": "\n".join(lines)},
            {"type": "image_url",
             "image_url": {"url": f"data:image/jpeg;base64,{image_b64}"}},
        ]},
    ]


def parse_vl_reply(text: str, criteria: list[str]) -> dict[str, int]:
    """Pull one score per criterion out of whatever the model actually said.

    Small models fence their JSON, prepend "Sure!", or answer with bare numbers.
    All three are recoverable; anything else is a failure and is reported as one
    rather than guessed at.
    """
    scores: dict[str, int] = {}
    start, end = text.find("{"), text.rfind("}")
    if start != -1 and end > start:
        try:
            doc = json.loads(text[start:end + 1])
            if isinstance(doc, dict):
                lowered = {str(k).strip().lower(): v for k, v in doc.items()}
                for name in criteria:
                    value = lowered.get(name.lower())
                    if isinstance(value, bool) or not isinstance(value, (int, float)):
                        continue
                    scores[name] = max(1, min(10, int(round(float(value)))))
        except (ValueError, TypeError):
            pass
    if len(scores) == len(criteria):
        return scores

    # Fall back to integers in order of appearance.
    found = []
    token = ""
    for ch in text:
        if ch.isdigit():
            token += ch
        else:
            if token:
                found.append(int(token))
                token = ""
    if token:
        found.append(int(token))
    usable = [n for n in found if 1 <= n <= 10]
    if len(usable) >= len(criteria):
        return {name: usable[i] for i, name in enumerate(criteria)}
    raise ValueError(f"no usable scores in reply: {text.strip()[:120]!r}")


def vl_render_bytes(res: Result, resample: int) -> str:
    """The image as the model will see it: same crop as the training render,
    scaled to something the projector will not immediately throw away."""
    bw, bh = res.bucket
    scale = min(1.0, VL_MAX_EDGE / max(bw, bh))
    size = (max(1, round(bw * scale)), max(1, round(bh * scale)))
    img, _fmt, _qt = load_source(res.path)
    try:
        out = img.resize(size, resample=resample, box=res.box)
    finally:
        img.close()
    buf = io.BytesIO()
    out.save(buf, "JPEG", quality=VL_JPEG_QUALITY, optimize=True)
    out.close()
    return base64.b64encode(buf.getvalue()).decode("ascii")


def vl_score_image(res: Result, cfg: VLConfig, resample: int) -> dict[str, int]:
    image_b64 = vl_render_bytes(res, resample)
    payload = {
        "model": cfg.model,
        "messages": build_vl_messages(cfg, image_b64),
        "temperature": 0,
        "seed": 0,
        "max_tokens": 200,
        "stream": False,
    }
    last = None
    for attempt in range(VL_RETRIES):
        try:
            doc = _http_json(cfg.chat_url, cfg.timeout, payload)
            text = doc["choices"][0]["message"]["content"]
            if isinstance(text, list):        # some servers return content parts
                text = "".join(part.get("text", "") for part in text
                               if isinstance(part, dict))
            return parse_vl_reply(text or "", cfg.criteria)
        except Exception as exc:
            last = exc
            if attempt < VL_RETRIES - 1:
                time.sleep(0.5 * (attempt + 1))
    raise RuntimeError(f"{type(last).__name__}: {last}")


def blend_scores(vl_mean: float, technical: float) -> float:
    """Weighted geometric mean of the model's opinion and the measured score.

    Geometric rather than arithmetic so that a low factor actually bites: an
    average lets a perfect critique carry a technically broken image, which is
    the whole thing this blend is supposed to prevent.
    """
    vl = max(1.0, min(10.0, vl_mean))
    tech = max(1.0, technical)
    return math.exp(VL_WEIGHT * math.log(vl) + (1.0 - VL_WEIGHT) * math.log(tech))


def load_vl_cache(prep_dir: Path, signature: str) -> dict:
    path = prep_dir / VL_CACHE_FILENAME
    if not path.is_file():
        return {}
    try:
        doc = json.loads(path.read_text(encoding="utf-8"))
        if doc.get("signature") != signature:
            return {}                        # different model, or different ask
        return doc.get("scores", {})
    except Exception:
        return {}


def save_vl_cache(prep_dir: Path, cfg: VLConfig, results: list[Result],
                  stamp: datetime) -> None:
    scores = {}
    for res in results:
        if not res.vl_scores:
            continue
        try:
            st = res.path.stat()
        except OSError:
            continue
        scores[res.name] = {"key": [st.st_size, st.st_mtime_ns],
                            "scores": res.vl_scores}
    doc = {
        "note": "k2prep --vl scores. Keyed to the model, the criteria and the "
                "prompt; change any of them and this file is discarded. Safe "
                "to delete.",
        "signature": cfg.signature(),
        "endpoint": cfg.endpoint,
        "model": cfg.model,
        "criteria": cfg.criteria,
        "updated": f"{stamp:%Y-%m-%d %H:%M:%S}",
        "scores": scores,
    }
    prep_dir.mkdir(parents=True, exist_ok=True)
    (prep_dir / VL_CACHE_FILENAME).write_text(
        json.dumps(doc, indent=1) + "\n", encoding="utf-8")


def apply_cached_vl(res: Result, cache: dict, criteria: list[str]) -> bool:
    entry = cache.get(res.name)
    if not entry:
        return False
    try:
        st = res.path.stat()
    except OSError:
        return False
    if list(entry.get("key", [])) != [st.st_size, st.st_mtime_ns]:
        return False
    scores = entry.get("scores") or {}
    if set(scores) != set(criteria):
        return False
    res.vl_scores = {k: int(v) for k, v in scores.items()}
    res.vl_mean = statistics.fmean(res.vl_scores.values())
    return True


@dataclass
class QualityTier:
    index: int                  # 1 = best
    name: str
    count: int = 0
    best: float = 0.0
    worst: float = 0.0
    score_hi: int = 0
    score_lo: int = 0
    gap_below: float | None = None   # size of the break under this tier
    tied_break: bool = False         # the break landed inside equal values


def plan_quality_tiers(scored: list[Result], n_tiers: int) -> list[QualityTier]:
    """Split the scored images into n_tiers by rank, best first.

    Mutates sort_tier on each result. Returns one QualityTier per tier, in
    order, including any that came out empty.
    """
    ordered = sorted(scored, key=lambda r: (-r.rank_fine, r.name))
    n = len(ordered)
    tiers = [QualityTier(index=i + 1, name=f"{QUALITY_DIR_PREFIX}{i + 1}")
             for i in range(n_tiers)]
    if n == 0:
        return tiers

    if n <= n_tiers:
        # Not enough images to fill every tier; hand them out from the top and
        # leave the rest empty rather than inventing distinctions.
        cuts = list(range(1, n))
    else:
        cuts = []
        window = max(1, round(QUALITY_CUT_WINDOW * n / n_tiers))
        floor_pos = 1
        for i in range(1, n_tiers):
            ideal = round(i * n / n_tiers)
            ceil_pos = n - (n_tiers - i)          # leave room for what follows
            lo = max(floor_pos, ideal - window)
            hi = min(ceil_pos, ideal + window)
            if lo > hi:
                lo = hi = max(floor_pos, min(ideal, ceil_pos))
            best_pos, best_key = lo, None
            for pos in range(lo, hi + 1):
                gap = ordered[pos - 1].rank_fine - ordered[pos].rank_fine
                key = (gap, -abs(pos - ideal))    # ties settle nearest the ideal
                if best_key is None or key > best_key:
                    best_key, best_pos = key, pos
            cuts.append(best_pos)
            floor_pos = best_pos + 1

    bounds = [0] + cuts + [n]
    for i in range(len(bounds) - 1):
        start, stop = bounds[i], bounds[i + 1]
        if start >= stop or i >= n_tiers:
            continue
        tier = tiers[i]
        group = ordered[start:stop]
        for res in group:
            res.sort_tier = tier.index
            res.sort_dirname = tier.name
        tier.count = len(group)
        tier.best = group[0].rank_fine
        tier.worst = group[-1].rank_fine
        # max/min rather than the endpoints: with --vl the ranking is the blend,
        # so the technical score is not monotone within a tier and the first and
        # last members are not its extremes.
        tier.score_hi = max(r.composite for r in group)
        tier.score_lo = min(r.composite for r in group)
        if stop < n:
            tier.gap_below = ordered[stop - 1].rank_fine - ordered[stop].rank_fine
            tier.tied_break = tier.gap_below <= EPS
    return tiers


def place_sorted(res: Result, prep_dir: Path, move: bool, force: bool,
                 dry_run: bool) -> None:
    """Put one source image, and its caption, in the folder for its score."""
    dest_dir = prep_dir / res.sort_dirname
    dest = dest_dir / res.name
    res.sort_dest = dest

    if dest.exists() and not force:
        res.sort_action = SORT_PRESENT
        return
    if dry_run:
        res.sort_action = SORT_MOVED if move else SORT_COPIED
        return

    dest_dir.mkdir(parents=True, exist_ok=True)
    caption = res.caption_src
    try:
        if move:
            if dest.exists():
                dest.unlink()
            shutil.move(str(res.path), str(dest))
            if caption is not None:
                cap_dest = dest_dir / caption.name
                if cap_dest.exists():
                    cap_dest.unlink()
                shutil.move(str(caption), str(cap_dest))
        else:
            shutil.copy2(res.path, dest)
            if caption is not None:
                shutil.copy2(caption, dest_dir / caption.name)
    except Exception as exc:
        res.sort_action = SORT_FAILED
        res.error = f"{type(exc).__name__}: {exc}"
        return
    res.sort_action = SORT_MOVED if move else SORT_COPIED


def find_stale_sorted(prep_dir: Path, results: list[Result]) -> list[str]:
    """Copies of a sorted file sitting in the wrong score folder.

    Only ever reported, never deleted. Under --move one of these may be the only
    surviving copy of a photograph, and no amount of tidiness is worth that
    risk; a stale entry after a band change is the user's to clear.
    """
    wanted = {r.name: r.sort_dirname for r in results if r.scored and r.sort_dirname}
    stale = []
    folders = [f"{SORT_DIR_PREFIX}{i}" for i in range(1, 11)]
    folders += [f"{QUALITY_DIR_PREFIX}{i}" for i in range(1, MAX_QUALITY_TIERS + 1)]
    for folder in folders:
        d = prep_dir / folder
        if not d.is_dir():
            continue
        for path in sorted(d.iterdir(), key=lambda p: p.name):
            if not path.is_file() or path.suffix.lower() == ".txt":
                continue
            target = wanted.get(path.name)
            if target is not None and target != folder:
                stale.append(f"{folder}/{path.name}   (this run files it under {target})")
    return stale


# ---------------------------------------------------------------------------
# --copy-to: selection and file placement
# ---------------------------------------------------------------------------
#
# Copies the ORIGINAL of every image that passes both gates - score and
# resolution - into a separate target folder, mirroring the source tree, with
# its .txt sidecar. shutil.copy2 copies bytes and keeps the mtime: nothing is
# decoded or re-encoded on the way.
#
# The source is read-only here as everywhere else, unless --move asks for the
# selected originals to leave it (place_move). The target is the user's
# folder, not k2prep's, so nothing in it is ever deleted, and a file that
# differs from the one this run would copy is reported, not overwritten, unless
# --force. Copies left by an earlier run that this run no longer selects are
# listed and left alone.

COPY_COPIED = "copied"
COPY_MOVED = "moved"
COPY_PRESENT = "already there"
COPY_CONFLICT = "conflict"
COPY_FAILED = "failed"

# copy2 keeps the mtime, but FAT and some network shares store it at 2 s
# resolution, so an exact comparison would call every re-run a conflict there.
COPY_MTIME_SLACK_NS = 2_000_000_000


def _path_inside(child: Path, parent: Path) -> bool:
    """True if child is parent or below it. Case-insensitive on Windows."""
    c = os.path.normcase(str(child))
    p = os.path.normcase(str(parent))
    try:
        return os.path.commonpath([c, p]) == p
    except ValueError:                            # different drives
        return False


def check_copy_target(source: Path, target: Path) -> str | None:
    """Why target cannot receive copies of source, or None if it can.

    The two must not overlap. A target that holds the source could put copies
    among the originals. A target inside the source would be scanned as source
    by the next --recursive run, so its copies would be scored and copied
    again - unless it sits under a folder the scan skips, which is any folder
    whose name starts with '_' or '.'.
    """
    if _path_inside(source, target):
        what = "is" if _path_inside(target, source) else "contains"
        return (f"the target folder {what} the source folder; copies could "
                f"land among the originals. Choose a folder outside {source}.")
    if _path_inside(target, source / PREP_DIRNAME):
        return (f"the target folder is inside {PREP_DIRNAME}, which belongs to "
                f"k2prep's own runs. Choose a folder outside it.")
    if _path_inside(target, source):
        rel = target.relative_to(source)
        if not any(part.startswith(("_", ".")) for part in rel.parts):
            return (f"the target folder is inside the source folder, so the "
                    f"next --recursive run would scan the copies as source. "
                    f"Choose a folder outside {source}, or one whose name "
                    f"starts with an underscore, e.g. {source / '_selected'}.")
    return None


def copy_dest_dir(target: Path, dataset: str, tier: int | None = None) -> Path:
    """target/<relpath>, mirroring the source tree; the root maps to target.
    With a tier (--by-tier), target/_<tier>/<relpath>: one folder per tier,
    each holding the whole source tree."""
    if tier is not None:
        target = target / by_tier_dirname(tier)
    return target / dataset if dataset else target


def _target_state(src: Path, dst: Path) -> str:
    """'absent', 'same' (the copy an earlier run made) or 'different'."""
    if not dst.exists():
        return "absent"
    if not dst.is_file():
        return "different"
    s, d = src.stat(), dst.stat()
    if (s.st_size == d.st_size
            and abs(s.st_mtime_ns - d.st_mtime_ns) <= COPY_MTIME_SLACK_NS):
        return "same"
    return "different"


def place_copy(res: Result, target: Path, force: bool, dry_run: bool) -> None:
    """Copy one source image, and its caption, to its mirrored place."""
    dest_dir = copy_dest_dir(target, res.dataset, res.dest_tier)
    pairs = [(res.path, dest_dir / res.path.name)]
    if res.caption_src is not None:
        pairs.append((res.caption_src, dest_dir / res.caption_src.name))
    res.copy_dest = pairs[0][1]

    try:
        states = [_target_state(src, dst) for src, dst in pairs]
    except OSError as exc:
        res.copy_action = COPY_FAILED
        res.error = f"{type(exc).__name__}: {exc}"
        return
    # The pair moves together: copying the image while its caption clashes
    # would leave a target image described by somebody else's caption.
    clash = [dst for (_src, dst), st in zip(pairs, states) if st == "different"]
    if clash and not force:
        res.copy_action = COPY_CONFLICT
        res.error = f"{clash[0].name} already exists in the target and differs"
        return
    todo = [(src, dst) for (src, dst), st in zip(pairs, states) if st != "same"]
    if not todo:
        res.copy_action = COPY_PRESENT
        return
    if dry_run:
        res.copy_action = COPY_COPIED
        return
    try:
        dest_dir.mkdir(parents=True, exist_ok=True)
        for src, dst in todo:
            shutil.copy2(src, dst)
    except Exception as exc:
        res.copy_action = COPY_FAILED
        res.error = f"{type(exc).__name__}: {exc}"
        return
    res.copy_action = COPY_COPIED


def place_move(res: Result, target: Path, force: bool, dry_run: bool,
               keep_caption: bool) -> None:
    """--move: move one source image, and its caption, to its mirrored place.

    What stays in the source is what was not selected, for a person to review.
    The guards are the copy's plus these, because this removes originals:

    - shutil.move renames within a volume and copies before it unlinks across
      volumes, so a file is in the target before it leaves the source.
    - The image and its caption leave together. If the second move fails, the
      first is moved back, so an image never ends up without its caption.
    - A target file that matches by size and mtime is the copy an earlier
      --copy-to made. That is enough to skip a copy but not to delete the only
      source, so here the bytes are compared, and the source is removed only
      when they agree. If they differ, it is a conflict.
    - keep_caption: another image still in the source uses this caption (x.jpg
      and x.png share x.txt), so it is copied, not moved.
    """
    dest_dir = copy_dest_dir(target, res.dataset, res.dest_tier)
    pairs = [(res.path, dest_dir / res.path.name, True)]
    if res.caption_src is not None:
        pairs.append((res.caption_src, dest_dir / res.caption_src.name,
                      not keep_caption))
    res.copy_dest = pairs[0][1]

    try:
        states = []
        for src, dst, _take in pairs:
            st = _target_state(src, dst)
            if st == "same" and not filecmp.cmp(src, dst, shallow=False):
                st = "different"
            states.append(st)
    except OSError as exc:
        res.copy_action = COPY_FAILED
        res.error = f"{type(exc).__name__}: {exc}"
        return
    clash = [dst for (_s, dst, _t), st in zip(pairs, states) if st == "different"]
    if clash and not force:
        res.copy_action = COPY_CONFLICT
        res.error = f"{clash[0].name} already exists in the target and differs"
        return
    if dry_run:
        res.copy_action = COPY_MOVED
        return

    moved: list[tuple[Path, Path]] = []
    try:
        dest_dir.mkdir(parents=True, exist_ok=True)
        for (src, dst, take), st in zip(pairs, states):
            if st == "same":
                continue
            if not take:
                shutil.copy2(src, dst)
                continue
            if st == "different":                 # --force, checked above
                dst.unlink()
            shutil.move(str(src), str(dst))
            moved.append((src, dst))
    except Exception as exc:
        # Across volumes, or when Windows refuses the rename of a file that is
        # open elsewhere, shutil.move copies and then unlinks; if the unlink
        # fails, the copy is left in the target beside an intact source. That
        # copy is only a duplicate, and only then is it removed.
        for (src, dst, take), st in zip(pairs, states):
            if not take or st != "absent" or (src, dst) in moved:
                continue
            try:
                if (src.is_file() and dst.is_file()
                        and filecmp.cmp(src, dst, shallow=False)):
                    dst.unlink()
            except OSError:
                pass
        stranded = []
        for src, dst in reversed(moved):
            try:
                shutil.move(str(dst), str(src))
            except Exception:
                stranded.append(dst.name)
        res.copy_action = COPY_FAILED
        res.error = f"{type(exc).__name__}: {exc}"
        if stranded:
            res.error += (f"; {', '.join(stranded)} reached the target and "
                          f"could not be moved back")
        return

    # A byte-identical file already in the target stands in for the move.
    try:
        for (src, _dst, take), st in zip(pairs, states):
            if st == "same" and take:
                src.unlink()
    except OSError as exc:
        res.copy_action = COPY_FAILED
        res.error = (f"{type(exc).__name__}: {exc}; the target holds an "
                     f"identical copy, the source was not removed")
        return
    res.copy_action = COPY_MOVED


def already_correct(path: Path, bucket: tuple[int, int]) -> bool:
    """7.3 idempotency: an existing output only counts as done if it is actually
    the image this run plans to write.

    Testing the filename alone is not enough. Toggling --no-merge, or any change
    that reassigns an image to a different bucket, keeps the same output name
    while changing its dimensions - and a stale file would then survive as a
    silent mismatch in the training set. Pillow reads the header lazily, so this
    costs no decode.
    """
    if not path.is_file():
        return False
    try:
        with Image.open(path) as img:
            return img.size == bucket
    except Exception:
        return False          # unreadable or truncated: rewrite it


def sweep_superseded(prep_dir: Path, datasets: list[str],
                     planned: dict[tuple[str, int], set[str]],
                     dry_run: bool) -> list[str]:
    """Remove tier-folder files this run does not place, and report them.

    A tier folder must end up holding exactly what the run planned, or the
    training set silently accumulates duplicates: change --threshold, or let the
    merge pass move an image to a different bucket, and yesterday's copy is
    still sitting there. _prep/ is generated output and is rebuilt from the
    source on demand, so clearing it is safe; the source folder is never
    touched by this or anything else.

    `datasets` is every directory the scan visited, not just those with
    accepted images: a dataset whose images all vanished or all fell below the
    threshold still gets its stale outputs cleared, exactly as an emptied
    folder always has in the flat layout.

    The other layout's tier folders of the same datasets are cleared too:
    switching --by-tier on or off rebuilds _prep in the new layout, and the
    old renders would otherwise sit beside the new ones. Only files are
    removed, never folders, so musubi's cache folders are left alone.
    """
    removed: list[str] = []
    seen: set[Path] = set()
    for layout in (_tier_first, not _tier_first):
        current = layout == _tier_first
        tiers = active_tiers() if current else (BY_TIER_TIERS if layout else TIERS)
        for ds in datasets:
            for tier in tiers:
                d = tier_dir(prep_dir, ds, tier, layout)
                if d in seen or not d.is_dir():
                    continue
                seen.add(d)
                keep = planned.get((ds, tier), set()) if current else set()
                for path in sorted(d.iterdir(), key=lambda p: p.name):
                    if not path.is_file() or path.name in keep:
                        continue
                    rel = d.relative_to(prep_dir).as_posix()
                    removed.append(f"{rel}/{path.name}")
                    if not dry_run:
                        path.unlink()
    return removed


def find_stale_datasets(prep_dir: Path, datasets: list[str]) -> list[str]:
    """Dataset folders under _prep whose source directory was not scanned this
    run - a renamed or deleted source subfolder leaves its outputs behind.

    Only ever reported, never deleted: removing whole trees over a rename is
    the kind of tidiness that costs someone an afternoon. The regenerated TOML
    does not reference them, so they cannot poison training either way.
    """
    known = set(datasets)
    tier_names = {str(t) for t in TIERS}
    tier_first_names = {by_tier_dirname(t) for t in BY_TIER_TIERS}
    stale: set[str] = set()

    def walk(d: Path, rel: str) -> None:
        try:
            entries = sorted(os.scandir(d), key=lambda e: e.name)
        except OSError:
            return
        for entry in entries:
            if not entry.is_dir(follow_symlinks=False):
                continue
            name = entry.name
            if rel == "" and (name == REPORTS_DIRNAME
                              or name in tier_first_names
                              or name.startswith((SORT_DIR_PREFIX,
                                                  QUALITY_DIR_PREFIX))):
                continue
            if name in tier_names:               # a tier folder: don't descend
                if rel not in known:
                    stale.add(rel)
                continue
            walk(Path(entry.path), qualified_name(rel, name))

    def walk_tier_first(d: Path, rel: str, tier_root: str) -> None:
        """_prep/_<tier>/<relpath>/: every folder holding files is a dataset."""
        try:
            entries = sorted(os.scandir(d), key=lambda e: e.name)
        except OSError:
            return
        if rel and rel not in known and any(e.is_file() for e in entries):
            stale.add(f"{tier_root}/{rel}")
        for entry in entries:
            if entry.is_dir(follow_symlinks=False) and entry.name != CACHE_DIRNAME:
                walk_tier_first(Path(entry.path), qualified_name(rel, entry.name),
                                tier_root)

    walk(prep_dir, "")
    for name in sorted(tier_first_names):
        if (prep_dir / name).is_dir():
            walk_tier_first(prep_dir / name, "", name)
    return sorted(stale)


